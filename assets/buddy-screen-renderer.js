// ─────────────────────── GFX-STYLE RENDERER ───────────────────────
class GFX {
  constructor(canvas) {
    canvas.width = W; canvas.height = H;
    this.ctx = canvas.getContext('2d');
    this.ctx.imageSmoothingEnabled = false;
  }
  fillScreen(c) { this.ctx.fillStyle = c; this.ctx.fillRect(0, 0, W, H); }
  fillRect(x, y, w, h, c) { this.ctx.fillStyle = c; this.ctx.fillRect(x, y, w, h); }
  drawPixel(x, y, c) { this.ctx.fillStyle = c; this.ctx.fillRect(x, y, 1, 1); }
  drawLine(x0, y0, x1, y1, c) {
    // Bresenham — matches what GFX draws on the device
    const dx = Math.abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    const dy = -Math.abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    let err = dx + dy;
    while (true) {
      this.drawPixel(x0, y0, c);
      if (x0 === x1 && y0 === y1) break;
      const e2 = 2 * err;
      if (e2 >= dy) { err += dy; x0 += sx; }
      if (e2 <= dx) { err += dx; y0 += sy; }
    }
  }
  fillCircle(cx, cy, r, c) {
    // Midpoint algorithm filled, matches Adafruit GFX
    for (let y = -r; y <= r; y++) {
      for (let x = -r; x <= r; x++) {
        if (x*x + y*y <= r*r) this.drawPixel(cx + x, cy + y, c);
      }
    }
  }
  drawChar(x, y, ch, color, size = 1) {
    // Adafruit classic font: 5 columns × 7 rows (LSB-top). Renders into a
    // 5*size × 8*size cell. Each font "pixel" becomes a size×size block.
    const code = ch.charCodeAt(0) & 0xFF;
    const offset = code * 5;
    for (let col = 0; col < 5; col++) {
      const colBits = FONT[offset + col];
      for (let row = 0; row < 8; row++) {
        if ((colBits >> row) & 1) {
          this.fillRect(x + col * size, y + row * size, size, size, color);
        }
      }
    }
  }
  drawText(x, y, text, color, size = 1) {
    let cx = x;
    for (const ch of text) {
      this.drawChar(cx, y, ch, color, size);
      cx += 6 * size; // 5 cols + 1 col spacing
    }
  }
  textWidth(text, size = 1) { return text.length * 6 * size; }
  drawTextRight(x, y, text, color, size = 1) {
    this.drawText(x - this.textWidth(text, size), y, text, color, size);
  }
  drawBitmap(x, y, bitmap, bw, bh, color) {
    const rowBytes = Math.ceil(bw / 8);
    for (let row = 0; row < bh; row++) {
      for (let col = 0; col < bw; col++) {
        const byte = bitmap[row * rowBytes + Math.floor(col / 8)];
        if (byte & (0x80 >> (col % 8))) {
          this.drawPixel(x + col, y + row, color);
        }
      }
    }
  }
  drawChevron(cx, cy, size, direction, color) {
    // Same shape the firmware draws (drawChevron in main.cpp)
    const tipX = cx + direction * size;
    const armX = cx - direction * size;
    for (let t = -1; t <= 1; t++) {
      this.drawLine(armX, cy - size + t, tipX, cy + t, color);
      this.drawLine(armX, cy + size + t, tipX, cy + t, color);
    }
  }
}

// ─────────────────────── ANIMATED STATUS INDICATOR ───────────────────────
function drawIndicator(gfx, status, cx, cy, color, accent, soft, frame) {
  // Mirrors drawStatusIndicatorAt() in src/main.cpp
  if (status === 'busy') {
    const active = frame % 3;
    for (let i = 0; i < 3; i++) {
      const x = cx - 8 + i * 8;
      const isActive = i === active;
      gfx.fillCircle(x, cy, isActive ? 3 : 2, isActive ? accent : color);
    }
    return;
  }
  if (status === 'done') {
    const c = frame % 2 ? accent : soft;
    gfx.drawLine(cx - 8, cy + 1, cx - 3, cy + 6, c);
    gfx.drawLine(cx - 3, cy + 6, cx + 8, cy - 7, c);
    gfx.drawLine(cx - 8, cy + 2, cx - 3, cy + 7, c);
    gfx.drawLine(cx - 3, cy + 7, cx + 8, cy - 6, c);
    return;
  }
  if (status === 'approval') {
    const c = frame % 2 ? accent : soft;
    gfx.drawLine(cx, cy - 8, cx + 9, cy, c);
    gfx.drawLine(cx + 9, cy, cx, cy + 8, c);
    gfx.drawLine(cx, cy + 8, cx - 9, cy, c);
    gfx.drawLine(cx - 9, cy, cx, cy - 8, c);
    gfx.fillRect(cx - 1, cy - 4, 3, 8, c);
    return;
  }
  if (status === 'question') {
    const c = frame % 2 ? accent : soft;
    gfx.drawText(cx - 5, cy - 7, '?', c, 2);
    return;
  }
  if (status === 'error') {
    // X cross — pulses accent/soft
    const c = frame % 2 ? accent : soft;
    for (let t = -1; t <= 1; t++) {
      gfx.drawLine(cx - 7 + t, cy - 7, cx + 7 + t, cy + 7, c);
      gfx.drawLine(cx - 7 + t, cy + 7, cx + 7 + t, cy - 7, c);
    }
    return;
  }
  // default: a single accent dot
  gfx.fillCircle(cx, cy, 3, accent);
}

// ─────────────────────── LOGO DRAWING ───────────────────────
function drawProviderLogo(gfx, provider, cx, cy, palette) {
  const tlx = cx - 24, tly = cy - 24;
  if (provider === 'codex') {
    gfx.drawBitmap(tlx, tly, OPENAI_BITMAP, 48, 48, palette.bg);
  } else if (provider === 'claude') {
    gfx.drawBitmap(tlx, tly, CLAUDE_BITMAP, 48, 48, palette.bg);
    gfx.drawBitmap(tlx, tly, CLAUDE_DETAIL_BITMAP, 48, 48, palette.accent);
  } else if (provider === 'pi') {
    gfx.drawBitmap(tlx, tly, PI_BITMAP, 48, 48, palette.bg);
  } else {
    // Buddy: procedural smiley like the firmware does
    gfx.fillCircle(cx, cy, 20, palette.bg);
    gfx.drawChar(cx - 22, cy - 22, ' ', palette.bg); // no-op placeholder
    // Outline ring
    for (let a = 0; a < 360; a += 4) {
      const rad = a * Math.PI / 180;
      gfx.drawPixel(Math.round(cx + Math.cos(rad) * 20), Math.round(cy + Math.sin(rad) * 20), palette.bg);
    }
    gfx.fillCircle(cx - 7, cy - 4, 2, palette.bg);
    gfx.fillCircle(cx + 7, cy - 4, 2, palette.bg);
    gfx.drawLine(cx - 7, cy + 5, cx - 2, cy + 9, palette.bg);
    gfx.drawLine(cx - 2, cy + 9, cx + 2, cy + 9, palette.bg);
    gfx.drawLine(cx + 2, cy + 9, cx + 7, cy + 5, palette.bg);
  }
}

// ─────────────────────── TEXT WRAP (for the title) ───────────────────────
function wrapText(text, maxCharsPerLine) {
  // Greedy word-wrap that breaks long single words at maxCharsPerLine boundary.
  const words = text.split(/\s+/);
  const lines = [];
  let cur = '';
  for (const w of words) {
    if (w.length > maxCharsPerLine) {
      if (cur) { lines.push(cur); cur = ''; }
      let rest = w;
      while (rest.length > maxCharsPerLine) {
        lines.push(rest.slice(0, maxCharsPerLine));
        rest = rest.slice(maxCharsPerLine);
      }
      cur = rest;
      continue;
    }
    const candidate = cur ? cur + ' ' + w : w;
    if (candidate.length <= maxCharsPerLine) cur = candidate;
    else { lines.push(cur); cur = w; }
  }
  if (cur) lines.push(cur);
  return lines;
}

function clampLines(lines, max) {
  if (lines.length <= max) return lines;
  const clipped = lines.slice(0, max);
  // append ellipsis dots to last line, trim chars if necessary
  let last = clipped[max - 1];
  const ellipsis = '...';
  // The font has  as a horizontal ellipsis (single-char) in Adafruit's classic.
  // Three dots is universally safe though.
  if (last.length + ellipsis.length > 40) { // bigger than any line will be
    last = last.slice(0, 40 - ellipsis.length);
  }
  // We always want to fit on the line; we'll truncate by what the caller passed.
  clipped[max - 1] = last + ellipsis;
  return clipped;
}

function truncateToWidth(text, maxChars) {
  if (text.length <= maxChars) return text;
  return text.slice(0, Math.max(0, maxChars - 3)) + '...';
}

// ─────────────────────── B2.2 LAYOUT ───────────────────────
const LAYOUT = {
  bannerH: 56,
  navH: 80,
  bodyPadX: 8,
  titleTopPad: 18,     // padding between banner bottom and first title line
  titleMetaGap: 12,    // gap between title block and meta line
  metaBottomPad: 14,   // padding between meta and nav top
  titleSize: 2,        // 12 px char w × 16 px line h
  metaSize: 2,         // bumped from 1 → 2 for readability
  // Banner is split into a vertical text stack and a fixed-position indicator
  // anchored to the right so it sits in the same place across all state lengths
  bannerIndCx: 220,    // fixed right-edge anchor for the animated icon
};

function drawScreen(gfx, opts, frame) {
  const { provider, status, agent, stateText, title, dir, branch, position, total } = opts;
  const palette = paletteFor(provider, status);

  // bg
  gfx.fillScreen(palette.bg);

  // ─── Banner (accent fill, 56 px tall) ───
  gfx.fillRect(0, 0, W, LAYOUT.bannerH, palette.accent);
  // Logo: 48×48 vertically centered (top y=4, center y=28 = banner middle).
  // The logo alone identifies the provider — no separate agent label.
  drawProviderLogo(gfx, provider, 4 + 24, LAYOUT.bannerH / 2, palette);

  // State text — horizontally CENTERED, vertically centered with the logo (y=28)
  const stateW = gfx.textWidth(stateText, 2);
  const stateX = Math.floor((W - stateW) / 2);
  const stateY = (LAYOUT.bannerH - 16) / 2; // size 2 = 16 px tall → top y=20, center y=28
  gfx.drawText(stateX, stateY, stateText, palette.bg, 2);

  // Animated indicator pinned at the right edge of the banner → consistent
  // position regardless of state-text length (logo / state / indicator triangle).
  drawIndicator(gfx, status, LAYOUT.bannerIndCx, LAYOUT.bannerH / 2,
                palette.bg, palette.bg, palette.bg, frame);

  // ─── Body (title + meta) ───
  const bodyTop = LAYOUT.bannerH + LAYOUT.titleTopPad;
  const bodyBottom = H - LAYOUT.navH;
  const innerW = W - 2 * LAYOUT.bodyPadX;

  const titleLineH = 8 * LAYOUT.titleSize;
  const titleCharW = 6 * LAYOUT.titleSize;
  const titleMaxCharsPerLine = Math.floor(innerW / titleCharW);

  const metaLineH = 8 * LAYOUT.metaSize;
  const metaCharW = 6 * LAYOUT.metaSize;
  const metaMaxChars = Math.floor(innerW / metaCharW);
  const metaY = bodyBottom - LAYOUT.metaBottomPad - metaLineH;

  // Title gets everything from bodyTop down to (metaY - titleMetaGap)
  const titleAreaH = metaY - LAYOUT.titleMetaGap - bodyTop;
  const titleMaxLines = Math.max(1, Math.floor(titleAreaH / titleLineH));
  let titleLines = wrapText(title, titleMaxCharsPerLine);
  titleLines = clampLines(titleLines, titleMaxLines);
  for (let i = 0; i < titleLines.length; i++) {
    gfx.drawText(LAYOUT.bodyPadX, bodyTop + i * titleLineH, titleLines[i], palette.fg, LAYOUT.titleSize);
  }

  // Meta line — size 2, single line, ellipsized to fit
  const metaParts = [];
  if (dir) metaParts.push(dir);
  if (branch) { metaParts.push(''); metaParts.push(branch); } //  = small dot
  const metaFull = metaParts.join('  ');
  const metaText = truncateToWidth(metaFull, metaMaxChars);
  gfx.drawText(LAYOUT.bodyPadX, metaY, metaText, palette.soft, LAYOUT.metaSize);

  // ─── Nav strip (80 px tall, chevrons + counter centered) ───
  const navTop = H - LAYOUT.navH;
  // top hairline divider
  for (let x = 0; x < W; x++) gfx.drawPixel(x, navTop, palette.panel);
  // chevrons at left/right thirds
  const chevronCy = navTop + LAYOUT.navH / 2;
  const canPrev = total > 1 && position > 1;
  const canNext = total > 1 && position < total;
  gfx.drawChevron(48, chevronCy, 12, -1, canPrev ? palette.accent : palette.panel);
  gfx.drawChevron(W - 48, chevronCy, 12, +1, canNext ? palette.accent : palette.panel);
  // central divider
  for (let y = navTop + 14; y < H - 8; y++) gfx.drawPixel(W / 2, y, palette.panel);
  // counter centered between chevrons (size 1)
  if (total > 0) {
    const counterText = `${position}/${total}`;
    const cw = gfx.textWidth(counterText, 1);
    const ch = 7;
    // small bg patch so the counter reads cleanly over the divider
    gfx.fillRect(W/2 - cw/2 - 2, chevronCy - 4, cw + 4, ch + 2, palette.bg);
    gfx.drawText(W/2 - cw/2, chevronCy - 3, counterText, palette.soft, 1);
  }
}

